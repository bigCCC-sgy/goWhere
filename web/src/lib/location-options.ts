export function cityKey(city?: string) {
  const normalized = (city || "").replace(/\s/g, "");
  if (!normalized) return "南京市";
  const match = allCities.find((item) => {
    const cityName = item.city || item.label;
    const aliases = item.aliases ?? [];
    return (
      normalized.includes(cityName.replace("市", "")) ||
      cityName.includes(normalized.replace("市", "")) ||
      aliases.some((alias) => normalized.toLowerCase().includes(alias.toLowerCase()))
    );
  });
  return match?.city || normalized;
}

export function popularAreasForCity(city?: string) {
  return popularAreasByCity[cityKey(city)] ?? [];
}

export function allStaticLocations() {
  return [...allCities, ...Object.values(popularAreasByCity).flat()];
}

export function localSuggestLocations(keyword: string, city?: string): LocationOption[] {
  const normalized = keyword.trim().toLowerCase();
  if (!normalized) return [];

  const cityScoped = city ? popularAreasForCity(city) : [];
  const candidates = [...cityScoped, ...allStaticLocations()];
  const seen = new Set<string>();

  return candidates
    .filter((item) => {
      const haystack = [
        item.label,
        item.city,
        item.district,
        item.address,
        item.keyword,
        ...(item.aliases ?? []),
      ]
        .filter(Boolean)
        .join(" ")
        .toLowerCase();
      return haystack.includes(normalized) || normalized.includes((item.keyword || item.label).toLowerCase());
    })
    .filter((item) => {
      const key = `${item.city}-${item.district}-${item.label}`;
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    })
    .slice(0, 10);
}

export function formatLocationLabel(location: UserLocation) {
  const parts = [location.city, location.district, shortName(location)].filter(Boolean);
  return parts.length ? Array.from(new Set(parts)).join(" · ") : location.label;
}

export function formatCompactLocationLabel(location: UserLocation) {
  const name = shortName(location);
  const parts = [location.district, name].filter(Boolean);
  return parts.length ? Array.from(new Set(parts)).join(" · ") : location.city || location.label;
}

export function locationToStorePatch(location: UserLocation & { areaCode?: string }): LocationPatch {
  const nextLocation: UserLocation = {
    ...location,
    label: formatLocationLabel(location),
  };
  return {
    userLocation: nextLocation,
    city: nextLocation.city || nextLocation.label || "全国",
    areaCode: location.areaCode || (nextLocation.source === "preset" ? "manual" : "manual"),
    location:
      nextLocation.longitude && nextLocation.latitude
        ? {
            longitude: nextLocation.longitude,
            latitude: nextLocation.latitude,
            label: nextLocation.label,
            city: nextLocation.city,
            district: nextLocation.district,
            address: nextLocation.address,
            source: nextLocation.source,
          }
        : undefined,
  };
}

function area(
  city: string,
  district: string,
  name: string,
  longitude: number,
  latitude: number,
  areaCode: string,
  aliases: string[],
): LocationOption {
  return {
    label: `${city} · ${district} · ${name}`,
    city,
    district,
    address: `${city}${district}${name}附近`,
    keyword: `${city.replace("市", "")} ${name}`,
    longitude,
    latitude,
    source: "preset",
    areaCode,
    aliases,
  };
}

function city(label: string, longitude?: number, latitude?: number, aliases: string[] = []): LocationOption {
  return {
    label,
    city: label,
    keyword: label.replace("市", ""),
    longitude,
    latitude,
    source: "preset",
    aliases: [label, label.replace("市", ""), ...aliases],
  };
}

function uniqueLocationOptions(items: LocationOption[]) {
  const seen = new Set<string>();
  return items.filter((item) => {
    const key = item.city || item.label;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

function shortName(location: UserLocation) {
  const label = location.label || location.keyword || "";
  const pieces = label.split("·").map((item) => item.trim()).filter(Boolean);
  return pieces[pieces.length - 1] || location.keyword || location.address || "";
}
